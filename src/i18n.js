  function resolveLocale(value) {
    if (value == null) return DEFAULT_LOCALE;
    var text = String(value).replace(/-/g, "_");
    var lower = text.toLowerCase();
    if (lower === "zh" || lower === "zh_cn") return "zh_CN";
    if (lower === "zh_tw" || lower === "zh_hk" || lower === "zh_hant") return "zh_TW";
    if (lower === "pt_br") return "pt_BR";
    if (lower === "pt" || lower === "pt_pt") return "pt";
    if (lower === "nb" || lower === "nn" || lower === "no") return "no";
    if (lower === "he" || lower === "iw") return "he";
    if (lower === "fil" || lower === "tl") return "fil";
    for (var i = 0; i < LOCALES.length; i++) {
      if (LOCALES[i].toLowerCase() === lower) return LOCALES[i];
    }
    return DEFAULT_LOCALE;
  }

  function pack(locale) {
    return MESSAGES[resolveLocale(locale)] || MESSAGES.en;
  }

  function translate(locale, key) {
    var value = pack(locale)[key];
    if (value == null || value === "") value = MESSAGES.en[key];
    return value || "";
  }

  function htmlLang(locale) {
    return resolveLocale(locale).replace(/_/g, "-");
  }

  function localeName(locale) {
    var resolved = resolveLocale(locale);
    return LOCALE_NAMES[resolved] || LOCALE_NAMES.en;
  }

  function filterLocales(query) {
    var q = String(query == null ? "" : query).trim().toLowerCase();
    if (!q) return LOCALES.slice();
    var matched = [];
    for (var i = 0; i < LOCALES.length; i++) {
      var code = LOCALES[i];
      var name = LOCALE_NAMES[code] || "";
      if (name.toLowerCase().indexOf(q) !== -1 || code.toLowerCase().indexOf(q) !== -1) matched.push(code);
    }
    return matched;
  }

  root.UbbI18n = {
    DEFAULT_LOCALE: DEFAULT_LOCALE,
    LOCALES: LOCALES,
    resolveLocale: resolveLocale,
    translate: translate,
    htmlLang: htmlLang,
    localeName: localeName,
    filterLocales: filterLocales,
    pack: pack,
    keys: function () {
      return Object.keys(MESSAGES.en);
    },
  };
